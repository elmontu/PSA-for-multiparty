bool test_wire_open_bit() {
    auto socks = coproto::LocalAsyncSocket::makePair();
    auto a = [&]() -> macoro::task<uint8_t> {
        co_return co_await mp::wireOpenBit(0, 0, socks[0]);
    };
    auto b = [&]() -> macoro::task<uint8_t> {
        co_return co_await mp::wireOpenBit(1, 1, socks[1]);
    };
    auto r = macoro::sync_wait(macoro::when_all_ready(a(), b()));
    uint8_t va = std::move(std::get<0>(r)).result();
    uint8_t vb = std::move(std::get<1>(r)).result();
    return va == 1 && vb == 1;
}

// Test wireSecureAnd produces the correct result for all (x, y) combos
// using a known-good Beaver triple (generated by R34a trusted dealer).
bool test_wire_secure_and_truth_table() {
    auto prng = makePrng(0x10);
    for (uint8_t xv : {uint8_t{0}, uint8_t{1}}) {
        for (uint8_t yv : {uint8_t{0}, uint8_t{1}}) {
            auto [x0, x1] = splitBit(xv, prng);
            auto [y0, y1] = splitBit(yv, prng);
            auto triple = mp::generateBeaverTripleBit(2, prng);

            auto socks = coproto::LocalAsyncSocket::makePair();
            auto p0 = [&]() -> macoro::task<uint8_t> {
                co_return co_await mp::wireSecureAndT(x0, y0, triple, 0, socks[0]);
            };
            auto p1 = [&]() -> macoro::task<uint8_t> {
                co_return co_await mp::wireSecureAndT(x1, y1, triple, 1, socks[1]);
            };
            auto r = macoro::sync_wait(macoro::when_all_ready(p0(), p1()));
            uint8_t z0 = std::move(std::get<0>(r)).result();
            uint8_t z1 = std::move(std::get<1>(r)).result();
            if (((z0 ^ z1) & 1) != ((xv & yv) & 1)) return false;
        }
    }
    return true;
}

