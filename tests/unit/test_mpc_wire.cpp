bool test_wire_secure_less_than_random() {
    auto prng = makePrng(0x12);
    for (int iter = 0; iter < 5; ++iter) {
        uint64_t xv = prng.get<uint64_t>();
        uint64_t yv = prng.get<uint64_t>();
        auto [x0, x1] = splitU64Bin(xv, prng);
        auto [y0, y1] = splitU64Bin(yv, prng);
        auto triples = mp::generateBeaverTripleBits(2, mp::wireSecureLessThanTripleCost(), prng);

        auto socks = coproto::LocalAsyncSocket::makePair();
        size_t idx0 = 0, idx1 = 0;
        auto p0 = [&]() -> macoro::task<uint8_t> {
            co_return co_await mp::wireSecureLessThan(x0, y0, triples, idx0, 0, socks[0]);
        };
        auto p1 = [&]() -> macoro::task<uint8_t> {
            co_return co_await mp::wireSecureLessThan(x1, y1, triples, idx1, 1, socks[1]);
        };
        auto r = macoro::sync_wait(macoro::when_all_ready(p0(), p1()));
        uint8_t z0 = std::move(std::get<0>(r)).result();
        uint8_t z1 = std::move(std::get<1>(r)).result();
        uint8_t expected = (xv < yv) ? 1 : 0;
        if (((z0 ^ z1) & 1) != expected) {
            std::cerr << "  iter=" << iter << " xv=" << xv << " yv=" << yv
                      << " expected=" << int(expected)
                      << " got=" << int((z0 ^ z1) & 1) << "\n";
            return false;
        }
        if (idx0 != mp::wireSecureLessThanTripleCost()) return false;
        if (idx1 != mp::wireSecureLessThanTripleCost()) return false;
    }
    return true;
}

bool test_wire_secure_equal_cases() {
    auto prng = makePrng(0x13);
    struct Case { uint64_t x, y; uint8_t expected; };
    std::vector<Case> cases = {
        {0, 0, 1}, {1, 1, 1}, {0, 1, 0},
        {0xDEADBEEFULL, 0xDEADBEEFULL, 1},
        {0xDEADBEEFULL, 0xDEADBEF0ULL, 0},
    };
    for (const auto& c : cases) {
        auto [x0, x1] = splitU64Bin(c.x, prng);
        auto [y0, y1] = splitU64Bin(c.y, prng);
        auto triples = mp::generateBeaverTripleBits(2, mp::wireSecureEqualTripleCost(), prng);

        auto socks = coproto::LocalAsyncSocket::makePair();
        size_t idx0 = 0, idx1 = 0;
        auto p0 = [&]() -> macoro::task<uint8_t> {
            co_return co_await mp::wireSecureEqual(x0, y0, triples, idx0, 0, socks[0]);
        };
        auto p1 = [&]() -> macoro::task<uint8_t> {
            co_return co_await mp::wireSecureEqual(x1, y1, triples, idx1, 1, socks[1]);
        };
        auto r = macoro::sync_wait(macoro::when_all_ready(p0(), p1()));
        uint8_t z0 = std::move(std::get<0>(r)).result();
        uint8_t z1 = std::move(std::get<1>(r)).result();
        if (((z0 ^ z1) & 1) != c.expected) return false;
    }
    return true;
}

// End-to-end: wire-AND using OLE-generated triples.
bool test_ole_triples_drive_wire_and() {
    // Generate 8 OLE triples; use 4 for the four (x,y) cases.
    const size_t count = 256;  // libOTe minimum
    auto socks_ole = coproto::LocalAsyncSocket::makePair();
    auto p0gen = [&]() -> macoro::task<std::vector<mp::BeaverTripleBit>> {
        oc::PRNG p = makePrng(0x21);
        auto t = co_await mp::oleGenerateTriples(0, count, p, socks_ole[0]);
        co_await socks_ole[0].flush();
        co_return t;
    };
    auto p1gen = [&]() -> macoro::task<std::vector<mp::BeaverTripleBit>> {
        oc::PRNG p = makePrng(0x22);
        auto t = co_await mp::oleGenerateTriples(1, count, p, socks_ole[1]);
        co_await socks_ole[1].flush();
        co_return t;
    };
    auto rgen = macoro::sync_wait(macoro::when_all_ready(p0gen(), p1gen()));
    auto t0 = std::move(std::get<0>(rgen)).result();
    auto t1 = std::move(std::get<1>(rgen)).result();

    // Merge per-party views into one bag with N=2 populated.
    auto prng = makePrng(0x20);
    std::vector<mp::BeaverTripleBit> merged(count);
    for (size_t i = 0; i < count; ++i) {
        merged[i].u = mp::SharedBit(2);
        merged[i].v = mp::SharedBit(2);
        merged[i].w = mp::SharedBit(2);
        merged[i].u.shares[0] = t0[i].u.shares[0];
        merged[i].u.shares[1] = t1[i].u.shares[1];
        merged[i].v.shares[0] = t0[i].v.shares[0];
        merged[i].v.shares[1] = t1[i].v.shares[1];
        merged[i].w.shares[0] = t0[i].w.shares[0];
        merged[i].w.shares[1] = t1[i].w.shares[1];
    }

    size_t tIdx = 0;
    for (uint8_t xv : {uint8_t{0}, uint8_t{1}}) {
        for (uint8_t yv : {uint8_t{0}, uint8_t{1}}) {
            auto [x0, x1] = splitBit(xv, prng);
            auto [y0, y1] = splitBit(yv, prng);
            auto socks = coproto::LocalAsyncSocket::makePair();
            const auto& tr = merged[tIdx++];
            auto p0 = [&]() -> macoro::task<uint8_t> {
                co_return co_await mp::wireSecureAndT(x0, y0, tr, 0, socks[0]);
            };
            auto p1 = [&]() -> macoro::task<uint8_t> {
                co_return co_await mp::wireSecureAndT(x1, y1, tr, 1, socks[1]);
            };
            auto r = macoro::sync_wait(macoro::when_all_ready(p0(), p1()));
            uint8_t z0 = std::move(std::get<0>(r)).result();
            uint8_t z1 = std::move(std::get<1>(r)).result();
            if (((z0 ^ z1) & 1) != ((xv & yv) & 1)) return false;
        }
    }
    (void)joinU64Bin;
    return true;
}

